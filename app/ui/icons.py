def app_icon(name: str, color: str | None = None) -> QIcon:
    """Load a Lucide SVG icon and tint its vector strokes for the active UI state.

    Icon keys remain stable for the application; the logo and OBS mark keep
    their original brand artwork.
    """
    icon = QIcon()
    svg_data = ICONS.get(name)
    if svg_data:
        if color is None:
            from app.ui.theme import Colors

            color = Colors.TEXT_MUTED
        tinted = svg_data.replace("currentColor", color)
        # Render the 24-unit SVG viewBox at a larger source size before Qt
        # caches the icon; this keeps 32–56 px callouts crisp as well.
        tinted = tinted.replace('width="24"', 'width="96"').replace(
            'height="24"', 'height="96"'
        )
        pixmap = QPixmap()
        pixmap.loadFromData(tinted.encode("utf-8"))
        icon.addPixmap(pixmap)
    return icon


def app_logo_icon() -> QIcon:
    """Return the main application logo icon from assets."""
    if LOGO_PATH.exists():
        return QIcon(str(LOGO_PATH))
    return app_icon("logo.svg")  # Fallback to embedded SVG


def app_logo_pixmap(size: int = 64) -> QPixmap:
    """Return the main application logo as a QPixmap."""
    if LOGO_PATH.exists():
        pixmap = QPixmap(str(LOGO_PATH))
        return pixmap.scaled(size, size)
    return QPixmap()
